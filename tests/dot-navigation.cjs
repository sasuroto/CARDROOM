const fs=require('node:fs'),assert=require('node:assert/strict'),ts=require('typescript');
for(const ext of ['.ts','.tsx'])require.extensions[ext]=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,esModuleInterop:true,target:ts.ScriptTarget.ES2022}}).outputText,f);
const React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const {default:DotLauncher,dotPickerMatches}=require('../app/dot-launcher.tsx');
const match=(id,date,league='ucl',home='Galatasaray')=>({id,date,league,home,away:'Stuttgart'});
const games=[match('late','2026-11-03T19:00Z'),match('early','2026-11-02T21:00Z'),match('next','2026-11-03T21:00Z'),match('bad','invalid'),match('other','2026-11-03T12:00Z','pl','Newcastle'),match('','2026-11-03T12:00Z')];
const before=JSON.stringify(games);
assert.deepEqual(dotPickerMatches(games,'2026-11-03','','all').map(x=>x.id),['early','other','late']);
assert.deepEqual(dotPickerMatches(games,'2026-11-03',' GALATA ','ucl').map(x=>x.id),['early','late']);
assert.deepEqual(dotPickerMatches(games,'2026-11-03','Stuttgart','pl').map(x=>x.id),['other']);
assert.equal(dotPickerMatches(games,'2026-11-03','Missing','all').length,0);
assert.equal(JSON.stringify(games),before,'filtering must not mutate cached events');
const html=renderToStaticMarkup(React.createElement(DotLauncher,{data:{leagues:[]}}));
assert.match(html,/aria-haspopup="dialog"/);
assert.match(html,/aria-label="Открыть DOT Predict"/);
assert.doesNotMatch(html,/<dialog/,'dialog and match requests are not mounted before opening');
assert.match(fs.readFileSync('app/global-search.tsx','utf8'),/<DotLauncher data=\{data\}\//);
assert.match(fs.readFileSync('app/dot-predict.tsx','utf8'),/className="dotPredict" aria-label="DOT Predict" tabIndex=\{-1\}/);
console.log('DOT navigation: 10 checks passed');
